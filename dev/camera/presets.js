// Camera presets: closeUp, twoShot, overShoulder, orbit (mid), dutch, crashZoom, heart iris (mid frame), letterbox.
qs.manual(true);
await qs.start({ seed: 5, playerGender: 'm', skipIntro: true });
qs.forceTeacher('writing', 999);
await qs.advance(0.3);
const cam = qs.ctx.cam, cast = qs.ctx.cast;
const crush = cast.get(qs.ctx.round.crushId);
const mate = cast.students().filter((c) => c !== crush && c.root.visible).sort((a, b) => a.root.position.distanceTo(crush.root.position) - b.root.position.distanceTo(crush.root.position))[0];
const scr = (ch) => { const v = ch.headWorld(new qs.ctx.THREE.Vector3()).project(cam.camera); return [+v.x.toFixed(2), +v.y.toFixed(2)]; };
const out = {};
const t = async (name, p, adv = 0.7) => { const r = p; await qs.advance(adv); out[name] = cam.debug().pos; await shot(name); return r; };
await t('p1-closeup', cam.closeUp(crush));
await t('p2-closeup-left', cam.closeUp(crush, { side: 'left', dist: 1.1, fov: 30 }));
await t('p3-twoshot', cam.twoShot(crush, mate, { dur: 0.5 }));
out.twoShotScreen = { crush: scr(crush), mate: scr(mate), crushPos: crush.root.position.toArray(), matePos: mate.root.position.toArray() };
await t('p4-overshoulder', cam.overShoulder(mate, crush, { dur: 0.5 }));
out.osScreen = { crush: scr(crush), mate: scr(mate) };
cam.orbit(cast.teacher, { radius: 1.6, fromYaw: 150, toYaw: 230, dur: 2 });
await t('p5-orbit-mid', null, 1.0);
cam.wide('classroom', { dur: 0 });
cam.dutch(14, 0.3);
await t('p6-wide-dutch', null, 0.5);
cam.crashZoom(cast.teacher, { dur: 0.25 });
await t('p7-crashzoom', null, 0.5);
cam.closeUp(crush, { dur: 0 });
cam.letterbox(true, 0.4);
cam.irisHeart('out', 1.0, crush);
await t('p8-iris-mid', null, 0.68);
await qs.advance(0.6);
out.afterIrisOut = cam.debug();
cam.irisHeart('in', 0.8);
await qs.advance(1.0);
cam.letterbox(false, 0.3);
await qs.advance(0.5);
out.afterIn = cam.debug();
return out;
