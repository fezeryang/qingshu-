// Title pan, first-person (aim / charging / studying), side + fpStay follow styles, landing freeze-frame.
qs.manual(true);
const cam = qs.ctx.cam, inp = qs.ctx.input, out = {};
await qs.advance(3);
out.title = cam.debug().mode;
await shot('c1-title');
await qs.start({ seed: 11, playerGender: 'f', skipIntro: true });
qs.forceTeacher('writing', 999);
inp.simulate({ nx: 0.35, ny: -0.1 });
await qs.advance(0.8);
out.aim = { yaw: +cam.fp.yaw.toFixed(3), pitch: +cam.fp.pitch.toFixed(3), fov: cam.camera.fov };
await shot('c2-aim');
inp.simulate({ down: 'Mouse0' });
await qs.advance(1.3);
out.charge = { fov: +cam.camera.fov.toFixed(2), power: qs.ctx.gameplay.aim.power };
await shot('c3-charge');
inp.simulate({ up: 'Mouse0' });   // releases → throws
await qs.advance(0.05);
out.afterRelease = cam.debug().mode;
await qs.advanceUntil(() => qs.ctx.flow.phase !== 'flight' && qs.ctx.flow.phase !== 'aim', 20);
await qs.start({ seed: 12, playerGender: 'm', skipIntro: true });
qs.forceTeacher('writing', 999);
inp.simulate({ nx: 0, ny: 0, down: 'Mouse2' });
await qs.advance(0.8);
out.study = { pitch: +cam.fp.pitch.toFixed(3), study: cam.fp.study };
await shot('c4-study');
inp.simulate({ up: 'Mouse2' });
await qs.advance(0.3);
cam.setFollowStyle('side');
await qs.throwAt('r1c3');
await qs.advance(0.7);
await shot('c5-side');
await qs.advanceUntil(() => qs.ctx.flow.phase !== 'flight' && qs.ctx.flow.phase !== 'aim', 20);
await qs.start({ seed: 13, playerGender: 'm', skipIntro: true });
qs.forceTeacher('writing', 999);
cam.setFollowStyle('fpStay');
await qs.throwAt('crush');
await qs.advance(0.8);
await shot('c6-fpstay');
cam.setFollowStyle('chase');
await qs.start({ seed: 14, playerGender: 'm', skipIntro: true });
qs.forceTeacher('writing', 999);
await qs.throwAt('crush');
await qs.advanceUntil(() => qs.ctx.gameplay.ball.state !== 'flying', 20);
await qs.advance(0.25);
out.landing = cam.debug();
await shot('c7-landing');
return out;
