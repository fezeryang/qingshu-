// qa/REPORT.md generator (owner: qs-qa-lead). The block between <!-- manual:start --> and
// <!-- manual:end --> is preserved across runs (visual scores, playtest notes, verdict commentary).
import fs from 'node:fs';
import path from 'node:path';
import { QA_DIR } from './session.mjs';

const AGENT = { world: 'qs-env-artist', characters: 'qs-character-artist', gameplay: 'qs-gameplay-engineer', ai: 'qs-ai-designer', camera: 'qs-camera-director', story: 'qs-narrative-director', ui: 'qs-ui-designer', audio: 'qs-audio-composer', core: 'lead', qa: 'qs-qa-lead' };
const CAT = { A: 'A. Boot and stability', B: 'B. Core loop with real input', C: 'C. Physics', D: 'D. Teacher AI', E: 'E. Endings', F: 'F. Camera', G: 'G. Visuals', H: 'H. Audio', I: 'I. Performance', J: 'J. Content quality' };

export const iconOf = (s) => (s.status === 'pass' ? '✅' : s.status === 'warn' ? '⚠️' : s.status === 'skip' ? '⏭️' : s.pending ? '⏳' : '❌');
const label = (s) => (s.status === 'fail' && s.pending ? 'pending' : s.status);
const esc = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function writeReport(res, prev, { strict = false } = {}) {
  const p = path.join(QA_DIR, 'REPORT.md');
  let manual = '\n_Manual notes (visual review scores, playtest notes) go here; this block is preserved when the report is regenerated._\n';
  try { const old = fs.readFileSync(p, 'utf8'); const m = old.match(/<!-- manual:start -->([\s\S]*?)<!-- manual:end -->/); if (m) manual = m[1]; } catch { /* first report */ }

  const specs = res.specs;
  const p0 = specs.filter((s) => s.priority === 'P0');
  const p0fail = p0.filter((s) => s.status === 'fail' && (!s.pending || strict));
  const p0pend = p0.filter((s) => s.status === 'fail' && s.pending && !strict);
  const anyStale = specs.some((s) => !res.ranIds.includes(s.id));
  const verdict = p0fail.length ? `❌ NOT RELEASABLE — ${p0fail.length} P0 item(s) failing${p0pend.length ? `, ${p0pend.length} more pending implementation` : ''}`
    : p0pend.length ? `⏳ NOT RELEASABLE YET — ${p0pend.length} P0 item(s) pending implementation`
      : specs.some((s) => s.status === 'fail' || s.status === 'warn') ? '⚠️ CONDITIONAL — no P0 failures; see warnings / P1 failures' : '✅ RELEASABLE';

  const count = (list, st) => list.filter((s) => label(s) === st).length;
  const rows = ['P0', 'P1'].map((pr) => { const l = specs.filter((s) => s.priority === pr); return `| ${pr} | ${l.length} | ${count(l, 'pass')} | ${count(l, 'warn')} | ${count(l, 'fail')} | ${count(l, 'pending')} | ${count(l, 'skip')} |`; });

  const out = [];
  out.push('# QA Report — 情书抛物线 (Love Letter Parabola)', '');
  out.push('<!-- auto:start (generated by tests/run.mjs — edit the manual block below instead) -->', '');
  out.push(`**Run:** ${res.generatedAt} · mode **${res.mode}**${strict ? ' (strict)' : ''} · ${res.durationSec}s · src hash \`${res.srcHash}\` · git \`${res.gitHead || '?'}\`${res.dirtyModules?.length ? ` + uncommitted changes in: ${res.dirtyModules.join(', ')}` : ''}`);
  out.push(`**Gray-box stub modules at run time:** ${res.stubs.length ? res.stubs.join(', ') : 'none'}`);
  if (anyStale) out.push(`**Note:** this run covered ${res.ranIds.join(', ')}; other rows are from earlier runs (see "ran" column).`);
  out.push('', `## Automatic verdict: ${verdict}`, '', '> The QA lead\'s judgement of these results (false positives, by-eye checks, visual scores, bug owners) is in the **QA verdict** section at the end of this file, and in `BUGS.md`.', '');
  out.push('| Priority | items | ✅ pass | ⚠️ warn | ❌ fail | ⏳ pending | ⏭️ skip |', '|---|---|---|---|---|---|---|', ...rows, '');
  out.push('Legend: ⏳ = fails only because the feature is not built yet (or its module is still a stub); counts as a failure with `--strict`.', '');

  out.push('## Results', '');
  for (const [letter, title] of Object.entries(CAT)) {
    const list = specs.filter((s) => s.id.startsWith(letter));
    if (!list.length) continue;
    out.push(`### ${title}`, '', '| ID | P | Status | Owner | Result | Evidence |', '|---|---|---|---|---|---|');
    for (const s of list) {
      const owner = s.owners.map((o) => AGENT[o] || o).join(', ');
      const ev = [...(s.data ? [`[data](${s.data})`] : []), ...s.evidence.slice(0, 6).map((e) => `[${path.basename(e)}](${e.startsWith('qa/') ? e.slice(3) : '../' + e})`)].join(' ');
      const stale = res.ranIds.includes(s.id) ? '' : ` _(ran ${s.ranAt.slice(0, 16)})_`;
      const det = esc(s.details).slice(0, 700) + (s.pending ? ` **[pending: ${esc(s.pending)}]**` : '') + (s.partial ? ' _(partial: quick mode)_' : '');
      out.push(`| ${s.id} | ${s.priority} | ${iconOf(s)} ${label(s)}${stale} | ${owner} | ${det} | ${ev} |`);
    }
    out.push('');
  }

  if (prev?.specs?.length) {
    const pm = new Map(prev.specs.map((s) => [s.id, s]));
    const ch = specs.filter((s) => pm.has(s.id) && label(pm.get(s.id)) !== label(s)).map((s) => `- ${s.id}: ${iconOf(pm.get(s.id))} ${label(pm.get(s.id))} → ${iconOf(s)} ${label(s)}`);
    out.push('## Changes since the previous full run', '', `Previous run: ${prev.generatedAt} (src \`${prev.srcHash}\`).`, '', ...(ch.length ? ch : ['- no status changes']), '');
  }

  out.push('## How each item is verified', '', '| ID | Method |', '|---|---|');
  for (const s of specs) out.push(`| ${s.id} | ${esc(s.method)} |`);
  out.push('', '<!-- auto:end -->', '', '<!-- manual:start -->' + manual + '<!-- manual:end -->', '');
  fs.writeFileSync(p, out.join('\n'));
  return p;
}
